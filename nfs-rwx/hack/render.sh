#!/bin/sh
# Regenerates ../install.yaml from the Helm chart, ../values.yaml and
# ../node-fencer.yaml, for people who install with plain `kubectl apply`. Run it after every change to
# values.yaml and commit both files together.
set -eu

CHART_REPO=https://kubernetes-sigs.github.io/nfs-ganesha-server-and-external-provisioner/
CHART_VERSION=1.8.0
NAMESPACE=nfs

cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# The server and the node fencer run the same image; their tags must match.
server_tag=$(sed -n 's/^  tag: "\(.*\)"$/\1/p' values.yaml)
fencer_tag=$(sed -n 's|^ *image: ghcr.io/exoscale-labs/nfs-rwx:||p' node-fencer.yaml)
if [ -z "$server_tag" ] || [ "$server_tag" != "$fencer_tag" ]; then
    echo "image tags differ: values.yaml '$server_tag', node-fencer.yaml '$fencer_tag'" >&2
    exit 1
fi

helm template nfs nfs-server-provisioner \
    --repo "$CHART_REPO" --version "$CHART_VERSION" \
    --namespace "$NAMESPACE" -f values.yaml > "$tmp/chart.yaml"

cp node-fencer.yaml "$tmp/"

cat > "$tmp/namespace.yaml" <<NS
apiVersion: v1
kind: Namespace
metadata:
  name: $NAMESPACE
NS

# helm template leaves namespaced objects without a namespace; kustomize sets
# it on those and leaves cluster-scoped ones alone.
cat > "$tmp/kustomization.yaml" <<KUST
namespace: $NAMESPACE
resources:
  - namespace.yaml
  - chart.yaml
  - node-fencer.yaml
KUST

# Written next to the target first, so a failure leaves the old file intact.
{
    echo "# Generated by hack/render.sh from values.yaml, node-fencer.yaml and the"
    echo "# nfs-server-provisioner chart $CHART_VERSION. Do not edit by hand."
    kubectl kustomize "$tmp"
} > install.yaml.tmp
mv install.yaml.tmp install.yaml
